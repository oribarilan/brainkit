#!/usr/bin/env node
// Generate `core/<name>.js` shim files at prepack time, one per `core/<name>.ts`
// source file (excluding tests). Each shim re-exports from its `.ts` sibling.
//
// Why this exists:
//
// `core/*.ts` files use `.js`-style import specifiers (e.g. `from "./types.js"`)
// because the CLI consumes the tsc-compiled `dist/core/*.js` output, where those
// specifiers resolve correctly under Node's strict ESM resolution.
//
// But the OpenCode plugin entrypoints (`opencode/server.ts`, `opencode/tui.tsx`)
// are loaded as raw TypeScript by bun and import `../core/index.ts` directly.
// When that source file does `export * from "./types.js"`, bun looks for
// `./types.js` next to it and finds nothing — the package only ships `.ts`
// sources for `core/`. Bun's `.js`→`.ts` fallback that works for project-local
// files does not fire for code under `node_modules/`. The plugin load fails
// (silently, except in the opencode log), and the user sees no theme, no logo,
// no sidebar.
//
// This script generates a thin `.js` shim alongside each `.ts` source so bun
// can resolve the `.js` specifier and follow the explicit `.ts` re-export.
// The shims are gitignored (clean dev tree) but ship in the npm tarball
// because `package.json` "files" includes `core/`.
//
// Long-term plan: migrate to `rewriteRelativeImportExtensions` (TS 5.7+) and
// drop this shim layer. Tracked as a follow-up.
//
// This module exports its helpers so tests can drive the generator against a
// temp directory instead of mutating the real `core/` (which races with
// parallel vitest workers importing `core/index.ts`).

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export function isShimmable(name) {
  if (!name.endsWith(".ts")) return false;
  if (name.endsWith(".d.ts")) return false;
  if (name.endsWith(".test.ts")) return false;
  if (name.endsWith(".spec.ts")) return false;
  return true;
}

export function listCoreSources(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  return entries.filter((e) => e.isFile() && isShimmable(e.name)).map((e) => e.name);
}

export function shimBody(tsFilename) {
  const base = tsFilename.slice(0, -".ts".length);
  // Explicit `.ts` extension so bun resolves to the source file directly,
  // bypassing the `.js`→`.ts` fallback that doesn't fire inside node_modules.
  return `// Auto-generated by scripts/generate-core-shims.mjs at prepack time.\n// Do not edit. See that script for rationale.\nexport * from "./${base}.ts";\n`;
}

export function writeShim(dir, tsFilename) {
  const base = tsFilename.slice(0, -".ts".length);
  const shimName = `${base}.js`;
  fs.writeFileSync(path.join(dir, shimName), shimBody(tsFilename), "utf-8");
  return shimName;
}

/**
 * Generate one `.js` shim per shippable `.ts` source in `dir`.
 * Returns the list of shim filenames written.
 */
export function generateShims(dir) {
  if (!fs.existsSync(dir)) {
    throw new Error(`core directory not found: ${dir}`);
  }
  const sources = listCoreSources(dir);
  if (sources.length === 0) {
    throw new Error(`no shippable *.ts source files found in: ${dir}`);
  }
  return sources.map((src) => writeShim(dir, src));
}

function main() {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const repoRoot = path.resolve(here, "..");
  const coreDir = path.join(repoRoot, "core");
  try {
    const written = generateShims(coreDir);
    console.log(`[generate-core-shims] wrote ${written.length} shim(s):`);
    for (const name of written) console.log(`  core/${name}`);
  } catch (err) {
    console.error(`[generate-core-shims] ${err instanceof Error ? err.message : String(err)}`);
    process.exit(1);
  }
}

// Only run as a CLI when invoked directly (not when imported by tests).
// `pathToFileURL` normalizes the entrypoint path on every platform (Windows
// drive letters, separators) so the comparison is portable.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
